// Bundles the Lucide SVGs in src/assets/icons into src/js/icons.js (no runtime fetch, works offline).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/assets/icons');
const icons = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(dir, file), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  icons[file.replace('.svg', '')] = inner.replace(/\s+/g, ' ').trim();
}
const out = `// Generated by scripts/gen-icons.mjs from Lucide (ISC license). Do not edit.\nexport const ICONS = ${JSON.stringify(icons, null, 2)};\n`;
writeFileSync(join(root, 'src/js/icons.js'), out);
console.log(`${Object.keys(icons).length} icons written`);
